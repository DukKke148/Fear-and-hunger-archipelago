"""Compact the v0.2 data table into the JS data file loaded by the game plugin."""
import json, sys

d = json.load(open(sys.argv[1], encoding='utf-8'))
CLS = {'progression': 0, 'useful': 1, 'filler': 2, 'trap': 3}
KIND = {'item': 'i', 'weapon': 'w', 'armor': 'a', 'access': 'x', 'trap': 't'}
items = {str(i['id']): [KIND[i['kind']], i['db_id'], CLS[i['classification']], i['name'], i['cat'][0],
                        i.get('power_rank'), i['native_tier'], i['etype'], 1 if i.get('teaches') else 0, 1 if i.get('priced') else 0] for i in d['items']}
zones, troops, keys, endings, names, skills, ending_pics, ending_ach = {}, {}, {}, {}, {}, {}, {}, {}
creature_loc = {}
recruits, recipes = {}, {}
for l in d['locations']:
    names[str(l['id'])] = l['name']
    t = l['type']
    if t == 'zone':
        for m in l['maps']:
            zones[str(m)] = l['id']
    elif t in ('bestiary', 'boss'):
        creature_loc[l['creature']] = [l['id'], t == 'boss']
    elif t == 'key':
        keys[str(l['item'])] = l['id']
    if t == 'ending':  # the endings of the goal (A, B, C, D, S), by switch
        endings[str(l['switch'])] = l['id']
    if t in ('ending', 'ending_extra'):
        for pic in l.get('pictures', []):
            ending_pics.setdefault(pic, []).append(l['id'])
        if l.get('achievement'):
            ending_ach[l['achievement']] = l['id']
    elif t == 'skill':
        skills[str(l['skill'])] = l['id']
    elif t in ('recruit', 'marriage'):  # actor id -> [location, 1 if it is the Marriage]
        recruits[str(l['actor'])] = [l['id'], 1 if t == 'marriage' else 0]
    elif t in ('cook', 'craft'):  # 'i:14' -> [location, 1 if cooking, 1 if campfire]
        recipes[l['result'][0] + ':' + str(l['result'][1])] = [l['id'], 1 if t == 'cook' else 0,
                                                               1 if l.get('campfire') else 0]
troop_loc = {l['troop']: l['id'] for l in d['locations'] if l['type'] == 'troop'}
for tr in d['troops']:
    cl = [creature_loc[c] for c in tr['creatures'] if c in creature_loc]
    troops[str(tr['id'])] = [troop_loc.get(tr['id'], 0), [c[0] for c in cl], any(c[1] for c in cl)]
out = dict(version=d['data_version'], game=d['game'], mapDepth=d['map_depth'], mapTier=d['map_tier'],
           tierNames=d['tiers'], noLockMaps=d['no_lock_maps'], mapFloor=d['map_floor'], floorNames=d['floors'],
           floorItems=d['floor_items'], spots=d['spots'], mapEntry=d['map_entry'], floorEntry=d['floor_entry'],
           mapNames=d['map_names'], skillTeachers={k: 1 for k in d['skill_teachers']},
           expectedSpots=d['expected_spots'], lootTables=d['loot_tables'], passItems=d['pass_items'],
           baseItems=d['base_items'], items=items, zones=zones, troops=troops, keys=keys, endings=endings, endingPictures=ending_pics, endingAchievements=ending_ach, endingMap=86, skills=skills,
           recruits=recruits, recipes=recipes, campfireEvents={k: 1 for k in d['campfire_events']},
           names=names)
js = ("// Generated by build_plugin_data_v2.py from Fear & Hunger v1.4.1 data. Do not edit by hand.\n"
      "/*:\n * @plugindesc Archipelago data for Fear & Hunger (load before ArchipelagoFH).\n * @author Julien\n */\n"
      "var APFH_DATA = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n")
open(sys.argv[2], 'w', encoding='utf-8').write(js)
print(len(d['spots']), 'spot events,', len(zones), 'zone maps,', len(troops), 'troops,', len(items), 'items,',
      len(js) // 1024, 'KB')
